export function translatePortfolioToEnglish(html) {
  const translate = text => {
    const key = text.trim();
    if (!Object.hasOwn(englishCopy, key)) return text;
    const offset = text.indexOf(key);
    return text.slice(0, offset) + englishCopy[key] + text.slice(offset + key.length);
  };
  return html
    .replace('<html lang="pt-BR">', '<html lang="en">')
    .replace(/>([^<>]+)</g, (_, text) => `>${translate(text)}<`)
    .replace(/\b(aria-label|alt|title|content)="([^"]*)"/g, (_, attribute, text) => `${attribute}="${translate(text)}"`);
}
